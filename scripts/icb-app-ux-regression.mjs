import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const read = p=>fs.readFileSync(p,'utf8');
const acknowledgement=read('app/lib/security-alert-acknowledgement.ts');
const js=ts.transpileModule(acknowledgement,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const sandbox={exports:{},require:()=>({})};vm.runInNewContext(js,sandbox);
const fingerprint=sandbox.exports.securityAlertFingerprint;
const event={alert_code:'login',occurred_at:'2026-10-03T00:00:00Z',message:'確認'};
assert.equal(fingerprint(null),'');assert.equal(fingerprint(event),fingerprint({...event}));
for(const field of ['alert_code','occurred_at','message'])assert.notEqual(fingerprint(event),fingerprint({...event,[field]:'new'}));
const controller=read('app/responsive-ux-controller.tsx');
for(const token of ['MutationObserver','document.createElement','supabase.rpc','appendChild','querySelector'])assert(!controller.includes(token),`controller must not mutate security DOM: ${token}`);
const search=read('app/schedule/search/page.tsx');
assert(search.includes('if (searching.current) return;') && search.includes('searching.current = false;'));
assert(search.includes('<form className="searchRow"') && search.includes('type="submit"'));
assert(search.includes('setRows([]);') && search.includes('setSearchFailed(true);'));
assert(search.includes('sessionStorage.getItem("icb-schedule-search")'));
assert(read('app/lib/client-security.ts').includes('sessionStorage.removeItem("icb-schedule-search")'));
const detail=read('app/schedule/detail/page.tsx');
assert(detail.includes('useSearchParams()') && detail.includes('},[entryId]);'));
assert(detail.includes('if(sequence !== loadSequence.current) return;'));
assert(detail.includes('setLoadFailed(true);') && detail.includes('>再試行</button>'));
assert(detail.includes('setEntry(current); setEntries(scheduleSet); setWork(workOrder);'));
const css=read('app/desktop-compact.css');assert(!css.includes('content:"車両検索"') && !css.includes('nth-child(8)'));
assert(read('app/home-dashboard.tsx').includes('margin: "0 0 12px"'));
assert(read('app/settings/login-history/page.tsx').includes('data-label="IPアドレス"'));
assert(read('app/loading.tsx').includes('role="status"'));
assert(read('app/not-found.tsx').includes('href="/"'));
console.log('ICB app UX regression: PASS (fingerprint semantics, source ownership, search, detail, responsive, route recovery)');

